// Copies ABIs + bytecode from Foundry artifacts into shared/ so every TS package uses the same source of truth.
import { readFileSync, writeFileSync } from "node:fs";

const names = ["KillswitchAccount", "KillswitchFactory", "MockERC20", "MockDEX"];
const file = (n: string) =>
  `contracts/out/${n}.sol/${n}.json`;

let abiTs = "// AUTO-GENERATED by scripts/export-abi.ts — do not edit\n";
const bytecode: Record<string, string> = {};
for (const n of names) {
  const art = JSON.parse(readFileSync(file(n), "utf8"));
  abiTs += `export const ${n}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
  bytecode[n] = art.bytecode.object;
}
writeFileSync("shared/abi.ts", abiTs);
writeFileSync("shared/bytecode.json", JSON.stringify(bytecode));
console.log("exported", names.join(", "));
